# === Statistical summary per config ===
# Group runs by config and print: per-seed final top-1, mean and sd across seeds,
# delta vs the 2/4/2 baseline with its standard error, train loss, best-epoch accuracy,
# parameter count and training minutes.
import json, glob, math, numpy as np
RUNS = '/content/drive/MyDrive/cornet_repro/runs'
g = {}
for f in sorted(glob.glob(f'{RUNS}/cornet_s_*.json')):
    r = json.load(open(f)); g.setdefault('-'.join(map(str, r['times'])), []).append(r)
base = np.array([r['final_top1'] for r in g['2-4-2']])
for k in ['1-1-1', '2-2-2', '2-4-2', '4-4-4']:
    rs = g[k]; fin = np.array([r['final_top1'] for r in rs])
    tl = np.array([r['history'][-1]['train_loss'] for r in rs])
    best = np.array([max(e['val_top1'] for e in r['history']) for r in rs])
    mins = [round(sum(e['secs'] for e in r['history'])/60) for r in rs]
    se = math.sqrt(fin.var(ddof=1)/len(fin) + base.var(ddof=1)/len(base)) if k != '2-4-2' else float('nan')
    print(k, 'n', len(fin), 'per-seed', np.round(fin, 2),
          '| mean %.2f sd %.2f' % (fin.mean(), fin.std(ddof=1)),
          '| delta %.2f se %.2f' % (fin.mean()-base.mean(), se),
          '| train loss mean %.3f sd %.3f' % (tl.mean(), tl.std(ddof=1)),
          '| best-epoch mean %.2f' % best.mean(),
          '| params %.2fM' % (rs[0]['params']/1e6), '| minutes', mins)